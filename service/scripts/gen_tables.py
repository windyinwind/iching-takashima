#!/usr/bin/env python3
"""Export the Python engine's static tables for the TypeScript port.

Everything that is plain data (preparation guides, source register, names, glosses, the
lunar table, reference tables) is dumped from the Python modules so it is never retyped.
Only the logic and the sentence templates are ported by hand.

Run from the repo root:  python3 service/scripts/gen_tables.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "skills/zhouyi-lookup/scripts"))

from zhouyi import calendar, derivation, english, guide, interpretation, japanese, takashima, trigrams  # noqa: E402

OUT = ROOT / "service/src/engine/tables.json"

tables = {
    "_note": "Generated by service/scripts/gen_tables.py from the Python engine. Do not edit.",
    "trigrams": {k: list(v) for k, v in trigrams.TRIGRAMS.items()},
    "symbols": trigrams.SYMBOLS,
    "nature": trigrams.NATURE,
    "elements": trigrams.ELEMENTS,
    "directions": trigrams.DIRECTIONS,
    "family": trigrams.FAMILY,
    "creatures": trigrams.CREATURES,
    "lunar_years": calendar.LUNAR_YEARS,
    "sources": interpretation.SOURCES,
    "hexagram_meaning": interpretation.HEXAGRAM_MEANING,
    "reference_tables": derivation.reference_tables(),
    "trigram_en": {k: list(v) for k, v in english.TRIGRAM_EN.items()},
    "hexagram_en": {str(k): list(v) for k, v in english.HEXAGRAM_EN.items()},
    "trigram_ja": {k: list(v) for k, v in japanese.TRIGRAM_JA.items()},
    "hexagram_ja": {str(k): list(v) for k, v in japanese.HEXAGRAM_JA.items()},
    "preparation": {"zh": guide.preparation(), "en": english.preparation(), "ja": japanese.preparation()},
    "sensitive_topics": sorted(takashima.SENSITIVE_TOPICS),
    "sensitive_tags": sorted(takashima.SENSITIVE_TAGS),
}

text = json.dumps(tables, ensure_ascii=False, indent=1) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
        sys.exit(f"{OUT} is out of date; run python3 service/scripts/gen_tables.py")
    print("tables.json OK")
else:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
